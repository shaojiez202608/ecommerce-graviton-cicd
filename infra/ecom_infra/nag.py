ANNOTATIONS = {
    "Annotation::@aws-cdk/aws-ecs:shouldUseCircuitBreaker": "Blue/green services do not use the rolling-update "
    "circuit breaker; failed green deployments keep traffic on blue and the deploy stage fails (see "
    "docs/architecture.md, Rollback).",
}


def acknowledgements(stack: Stack, project: str, prefix: str, env: str | None) -> list[Acknowledgment]:
    kind = stack.stack_name.rsplit("-", 1)[-1]
    rules = {**COMMON, **BY_KIND.get(kind, {})}
    region = stack.region
    out = []
    for rule, reason in rules.items():
        rule_id = P + rule.format(region=region, env=env or "", prefix=prefix, project=project)
        out.append(Acknowledgment(id=rule_id, reason=reason))
    if kind == "platform":
        out.extend(Acknowledgment(id=i, reason=r) for i, r in ANNOTATIONS.items())
    return out


def apply_suppressions(stack: Stack, project: str, prefix: str, env: str | None) -> None:
    Validations.of(stack).acknowledge(*acknowledgements(stack, project, prefix, env))
