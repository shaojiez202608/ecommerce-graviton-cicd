BY_KIND = {"cicd": CICD, "platform": PLATFORM, "mcf": MCF}


def _relative(stack: Stack, node: IConstruct) -> str:
    return node.node.path[len(stack.node.path) + 1:]


def acknowledgements(stack: Stack, app_cfg: AppConfig, env_cfg: EnvConfig | None) -> list[tuple[IConstruct, Acknowledgment]]:
    kind = stack.stack_name.rsplit("-", 1)[-1]
    entries = [*BY_KIND.get(kind, []), *(ANNOTATIONS if kind == "platform" else [])]
    nodes = [n for n in stack.node.find_all() if n is not stack]
    fmt = {"region": stack.region, "env": env_cfg.name if env_cfg else "", "prefix": app_cfg.ssm_prefix,
           "project": app_cfg.project}
    out = []
    for ack in entries:
        if ack.when is not None and not ack.when(app_cfg, env_cfg):
            continue
        matched = [n for n in nodes if fnmatchcase(_relative(stack, n), ack.path)]
        if not matched:
            raise ValueError(f"{stack.stack_name}: nag acknowledgement path {ack.path!r} matches no construct")
        finding = ack.finding if ack.finding.startswith("Annotation::") else P + ack.finding.format(**fmt)
        out.extend((n, Acknowledgment(id=finding, reason=ack.reason)) for n in matched)
    return out


def apply_suppressions(stack: Stack, app_cfg: AppConfig, env_cfg: EnvConfig | None) -> None:
    for node, ack in acknowledgements(stack, app_cfg, env_cfg):
        Validations.of(node).acknowledge(ack)
