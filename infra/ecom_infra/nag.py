"""cdk-nag (v3, AwsSolutions pack) acknowledgements, attached to the exact constructs they apply to.

Every entry names a construct path (glob, relative to the stack), the finding id and a written
reason; SECURITY-NOTES.md summarises the same list. Nothing is acknowledged stack-wide: an entry
whose path matches no construct raises (so the list cannot silently drift from the stacks), and
entries that only apply to some environments carry a condition.
Finding templates use {region}, {env}, {prefix} and {project}; no account ID appears (it stays a token).
"""

